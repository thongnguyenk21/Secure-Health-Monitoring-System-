//! Generates `shared/rust/src/generated.rs` from the Protobuf contracts.
//!
//! Usage (normally through `tools/scripts/gen-contracts.sh`):
//! - `iomt-codegen` regenerates the file;
//! - `iomt-codegen --check` fails if the committed file differs from a fresh
//!   generation, so CI catches hand edits and contracts changed without codegen.
//!
//! Both modes also encode every example in `shared/protocols/examples/` with
//! protoc, so an example that no longer matches its message fails the run.
//!
//! The generated code is committed instead of produced by a `build.rs`: crates
//! that depend on `iomt-protocol` (edge services cross-compiled for the Pi, the
//! cloud backend) then build without protoc.

use std::collections::BTreeMap;
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode, Stdio};

const HEADER: &str = "\
// @generated by shared/rust/codegen from shared/protocols/proto. DO NOT EDIT.
// Regenerate with tools/scripts/gen-contracts.sh.
";

fn main() -> ExitCode {
    let check = std::env::args().any(|a| a == "--check");
    match run(check) {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("iomt-codegen: {e}");
            ExitCode::FAILURE
        }
    }
}

/// Runs generation, then either writes the result or compares it.
///
/// # Arguments
/// * `check` - when `true`, compare with the committed file instead of writing it.
///
/// # Errors
/// Returns a message naming the failing step and what to do about it.
fn run(check: bool) -> Result<(), String> {
    let manifest = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let rust_dir = manifest
        .parent()
        .ok_or("codegen crate has no parent directory")?
        .to_path_buf();
    let protocols = rust_dir.join("../protocols");
    let proto_root = protocols.join("proto");
    let target = rust_dir.join("src/generated.rs");
    let protoc = protoc_bin_vendored::protoc_bin_path()
        .map_err(|e| format!("cannot locate the vendored protoc: {e}"))?;

    let protos = find_files(&proto_root, "proto")?;
    if protos.is_empty() {
        return Err(format!("no .proto files under {}", proto_root.display()));
    }

    let generated = generate(&protoc, &proto_root, &protos)?;
    let formatted = rustfmt(&rust_dir, &generated)?;
    check_examples(&protoc, &proto_root, &protos, &protocols.join("examples"))?;

    if check {
        let current = fs::read_to_string(&target).unwrap_or_default();
        if current != formatted {
            return Err(format!(
                "{} is out of date with the contracts; run tools/scripts/gen-contracts.sh \
                 and commit the result",
                target.display()
            ));
        }
        println!("generated.rs is up to date");
    } else {
        fs::write(&target, formatted)
            .map_err(|e| format!("cannot write {}: {e}", target.display()))?;
        println!("wrote {}", target.display());
    }
    Ok(())
}

/// Lists files with the given extension under `dir`, sorted for stable output.
///
/// # Arguments
/// * `dir` - directory to walk recursively.
/// * `ext` - extension without the dot, e.g. `"proto"`.
///
/// # Errors
/// Returns a message if a directory cannot be read.
fn find_files(dir: &Path, ext: &str) -> Result<Vec<PathBuf>, String> {
    let mut out = Vec::new();
    if !dir.exists() {
        return Ok(out);
    }
    let entries = fs::read_dir(dir).map_err(|e| format!("cannot read {}: {e}", dir.display()))?;
    for entry in entries {
        let path = entry
            .map_err(|e| format!("cannot read {}: {e}", dir.display()))?
            .path();
        if path.is_dir() {
            out.extend(find_files(&path, ext)?);
        } else if path.extension().is_some_and(|e| e == ext) {
            out.push(path);
        }
    }
    out.sort();
    Ok(out)
}

/// Runs prost/tonic and nests each package file into one module tree.
///
/// # Arguments
/// * `protoc` - path to the protoc binary.
/// * `proto_root` - include root; package `a.b.v1` lives under `a/b/v1/`.
/// * `protos` - every `.proto` file to compile.
///
/// # Returns
/// Unformatted Rust source with `pub mod a { pub mod b { pub mod v1 { .. } } }`.
///
/// # Errors
/// Returns a message if protoc or the code generator fails.
fn generate(protoc: &Path, proto_root: &Path, protos: &[PathBuf]) -> Result<String, String> {
    let out_dir = std::env::temp_dir().join(format!("iomt-codegen-{}", std::process::id()));
    fs::create_dir_all(&out_dir)
        .map_err(|e| format!("cannot create {}: {e}", out_dir.display()))?;

    let mut config = prost_build::Config::new();
    config.protoc_executable(protoc);
    let result = tonic_prost_build::configure()
        .build_server(true)
        .build_client(true)
        .out_dir(&out_dir)
        .compile_with_config(config, protos, &[proto_root.to_path_buf()])
        .map_err(|e| format!("protoc failed on the contracts: {e}"));

    let assembled = result.and_then(|()| assemble(&out_dir));
    let _ = fs::remove_dir_all(&out_dir);
    assembled
}

/// One level of the module tree built from package names.
#[derive(Default)]
struct ModuleNode {
    /// Code of the package that ends at this level, if any.
    body: String,
    /// Child modules, sorted by name for stable output.
    children: BTreeMap<String, ModuleNode>,
}

impl ModuleNode {
    /// Appends this node's code and its children as nested `pub mod` blocks.
    fn render(&self, out: &mut String) {
        out.push_str(&self.body);
        for (name, child) in &self.children {
            out.push_str(&format!("pub mod {name} {{\n"));
            child.render(out);
            out.push_str("}\n");
        }
    }
}

/// Merges every `<package>.rs` file from prost into one module tree.
///
/// Packages share prefixes (`iomt.firmware.v1`, `iomt.telemetry.v1`), so each
/// module is opened once and holds all of its sub-packages.
///
/// # Errors
/// Returns a message if the output directory cannot be read.
fn assemble(out_dir: &Path) -> Result<String, String> {
    let mut root = ModuleNode::default();
    for file in find_files(out_dir, "rs")? {
        let package = file
            .file_stem()
            .and_then(|s| s.to_str())
            .ok_or_else(|| format!("unexpected generated file {}", file.display()))?;
        let body = fs::read_to_string(&file)
            .map_err(|e| format!("cannot read {}: {e}", file.display()))?;
        let node = package.split('.').fold(&mut root, |node, segment| {
            node.children.entry(segment.to_owned()).or_default()
        });
        node.body.push_str(&body);
    }
    let mut source = String::from(HEADER);
    root.render(&mut source);
    Ok(source)
}

/// Formats Rust source with the repository rustfmt settings.
///
/// # Arguments
/// * `cwd` - directory rustfmt searches upward from for `rustfmt.toml`.
/// * `source` - unformatted Rust code.
///
/// # Errors
/// Returns a message if rustfmt is missing or rejects the code.
fn rustfmt(cwd: &Path, source: &str) -> Result<String, String> {
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout"])
        .current_dir(cwd)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|e| {
            format!("cannot start rustfmt ({e}); install it with `rustup component add rustfmt`")
        })?;
    child
        .stdin
        .take()
        .ok_or("rustfmt has no stdin")?
        .write_all(source.as_bytes())
        .map_err(|e| format!("cannot send code to rustfmt: {e}"))?;
    let output = child
        .wait_with_output()
        .map_err(|e| format!("rustfmt did not finish: {e}"))?;
    if !output.status.success() {
        return Err(format!(
            "rustfmt rejected the generated code: {}",
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    String::from_utf8(output.stdout).map_err(|e| format!("rustfmt output is not UTF-8: {e}"))
}

/// Encodes each `<full.message.Name>[--label].txtpb` example with protoc.
///
/// # Arguments
/// * `examples` - directory of text-format examples; the file stem is the
///   fully qualified message name, e.g. `iomt.telemetry.v1.UploadBatchRequest`,
///   optionally followed by `--label` so one message can have several examples
///   (`iomt.firmware.v1.LinkControl--hello.txtpb`).
///
/// # Errors
/// Returns a message naming the first example that does not match its message.
fn check_examples(
    protoc: &Path,
    proto_root: &Path,
    protos: &[PathBuf],
    examples: &Path,
) -> Result<(), String> {
    for example in find_files(examples, "txtpb")? {
        let message = example
            .file_stem()
            .and_then(|s| s.to_str())
            .and_then(|s| s.split("--").next())
            .ok_or_else(|| format!("unexpected example name {}", example.display()))?;
        let input = fs::File::open(&example)
            .map_err(|e| format!("cannot open {}: {e}", example.display()))?;
        let output = Command::new(protoc)
            .arg(format!("--encode={message}"))
            .arg(format!("-I{}", proto_root.display()))
            .args(protos)
            .stdin(input)
            .stdout(Stdio::null())
            .stderr(Stdio::piped())
            .output()
            .map_err(|e| format!("cannot run protoc: {e}"))?;
        if !output.status.success() {
            return Err(format!(
                "example {} does not match message {message}: {}",
                example.display(),
                String::from_utf8_lossy(&output.stderr).trim()
            ));
        }
    }
    Ok(())
}
